-- Identity columns: ALWAYS and BY DEFAULT survive flush, hydrate-on-write, new inserts and unmanage.

\set VERBOSITY terse
\set ON_ERROR_STOP off

CREATE FUNCTION sqlreg.fingerprint(rel regclass, ord text) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE result text;
BEGIN
  EXECUTE format('SELECT md5(coalesce(string_agg(t::text, ''|'' ORDER BY %s), '''')) FROM %s t', ord, rel) INTO result;
  RETURN result;
END
$$;

CREATE TABLE sqlreg.idt (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  seq2 int GENERATED BY DEFAULT AS IDENTITY,
  body text
);
INSERT INTO sqlreg.idt (body) SELECT 'row' || g FROM generate_series(1, 60) g;
CREATE TABLE sqlreg.idt_ctl AS SELECT * FROM sqlreg.idt;
SELECT sqlreg.fingerprint('sqlreg.idt', 'id') AS before_flush \gset

SELECT koldstore.manage_table(
  table_name => 'sqlreg.idt'::regclass, storage => 'sqlreg_fs', hot_row_limit => 5,
  min_flush_rows => 1, max_rows_per_file => 20, migration_order_by => 'id', auto_flush => false
) IS NOT NULL AS idt_managed;
SELECT sqlreg.flush_table('sqlreg.idt'::regclass) IS NOT NULL AS idt_flushed;
SELECT sqlreg.fingerprint('sqlreg.idt', 'id') = :'before_flush' AS same_after_flush;

SET koldstore.hydrate_on_write = on;
UPDATE sqlreg.idt SET body = 'changed' WHERE id IN (3, 40);
UPDATE sqlreg.idt_ctl SET body = 'changed' WHERE id IN (3, 40);
UPDATE sqlreg.idt SET seq2 = 999 WHERE id = 7;
UPDATE sqlreg.idt_ctl SET seq2 = 999 WHERE id = 7;
DELETE FROM sqlreg.idt WHERE id = 9;
DELETE FROM sqlreg.idt_ctl WHERE id = 9;
RESET koldstore.hydrate_on_write;
INSERT INTO sqlreg.idt (body) VALUES ('fresh');
SELECT id FROM sqlreg.idt WHERE body = 'fresh';
SELECT koldstore.wait_for_async_mirror() IS NOT NULL AS mirror_caught_up;
SELECT count(*) AS rows_visible FROM sqlreg.idt;
SELECT sqlreg.flush_table('sqlreg.idt'::regclass, true) IS NOT NULL AS idt_reflushed;
SELECT count(*) AS rows_after_reflush, max(id) AS max_id FROM sqlreg.idt;

SELECT koldstore.unmanage_table('sqlreg.idt'::regclass, true, true) IS NOT NULL AS idt_unmanaged;
SELECT count(*) AS rows_after_unmanage, max(id) AS max_id FROM sqlreg.idt;
INSERT INTO sqlreg.idt (body) VALUES ('after unmanage');
SELECT id FROM sqlreg.idt WHERE body = 'after unmanage';
