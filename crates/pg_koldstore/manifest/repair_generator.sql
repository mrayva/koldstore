-- Generates repair_objects.json from a freshly created database (run by scripts/check-sql-drift.sh
-- --update-expected, never at run time). The catalog placeholder in the WITH clause below is replaced by
-- object_manifest.sql, so a repair entry is keyed by exactly the line the drift check compares.
--
--   functions: line -> {name, create (full definition), add (signature for ALTER EXTENSION ... ADD),
--                       revoke_public}
--   columns:   line -> {table, add (ALTER TABLE ... ADD COLUMN ...), needs_default}
--   tables:    name -> {create, constraints[], foreign_keys[], indexes[]}   (creation order)
WITH cat AS (@CATALOG@)
SELECT jsonb_pretty(jsonb_build_object(
  'functions', COALESCE((
    SELECT jsonb_object_agg(c.line, jsonb_build_object(
             'name', p.proname,
             'create', pg_get_functiondef(c.ref_oid),
             'add', format('%I.%I(%s)', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)),
             'revoke_public', NOT has_function_privilege('public', c.ref_oid, 'EXECUTE')))
    FROM cat c
    JOIN pg_proc p ON p.oid = c.ref_oid
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE c.kind = 'function'), '{}'::jsonb),
  'columns', COALESCE((
    SELECT jsonb_object_agg(c.line, jsonb_build_object(
             'table', r.relname,
             'add', format('ALTER TABLE %I.%I ADD COLUMN %I %s%s%s', n.nspname, r.relname, a.attname,
                           format_type(a.atttypid, a.atttypmod),
                           COALESCE(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), ''),
                           CASE WHEN a.attnotnull AND d.adbin IS NOT NULL THEN ' NOT NULL' ELSE '' END),
             'needs_default', a.attnotnull AND d.adbin IS NULL,
             'unsupported', a.attidentity <> '' OR a.attgenerated <> ''))
    FROM cat c
    JOIN pg_class r ON r.oid = c.ref_oid
    JOIN pg_namespace n ON n.oid = r.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.ref_oid AND a.attnum = c.ref_num
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE c.kind = 'column'), '{}'::jsonb),
  'tables', COALESCE((
    SELECT jsonb_object_agg(t.relname, jsonb_build_object(
      'create', format('CREATE TABLE %I.%I (%s)', t.nspname, t.relname, (
          SELECT string_agg(format('%I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                                   CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                                      WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
                                   COALESCE(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), ''),
                                   CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END),
                            ', ' ORDER BY a.attnum)
          FROM pg_attribute a
          LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum AND a.attidentity = ''
          WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped)),
      'constraints', COALESCE((
          SELECT jsonb_agg(format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s', t.nspname, t.relname, k.conname,
                                  pg_get_constraintdef(k.oid)) ORDER BY k.conname)
          FROM pg_constraint k WHERE k.conrelid = t.oid AND k.contype IN ('p', 'u', 'c')), '[]'::jsonb),
      'foreign_keys', COALESCE((
          SELECT jsonb_agg(format('ALTER TABLE %I.%I ADD CONSTRAINT %I %s', t.nspname, t.relname, k.conname,
                                  pg_get_constraintdef(k.oid)) ORDER BY k.conname)
          FROM pg_constraint k WHERE k.conrelid = t.oid AND k.contype = 'f'), '[]'::jsonb),
      'indexes', COALESCE((
          SELECT jsonb_agg(pg_get_indexdef(i.indexrelid) ORDER BY ic.relname)
          FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid
          WHERE i.indrelid = t.oid AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid)),
          '[]'::jsonb)
    ) ORDER BY t.relname)
    FROM (SELECT DISTINCT r.oid, r.relname, n.nspname
          FROM cat c JOIN pg_class r ON r.oid = c.ref_oid JOIN pg_namespace n ON n.oid = r.relnamespace
          WHERE c.kind = 'column') t), '{}'::jsonb)
))
