#!/usr/bin/env bash
# Read-your-writes across a leader and a follower: the leader's publish returns a publication number,
# and wait_for_publication() on the follower returns once it has applied that publication (two scratch
# clusters, shared filesystem storage). Pass/fail.
# Usage: KOLDSTORE_PKG=<cargo pgrx package output dir> [PG_BIN=...] [RYW_TEST_DIR=...] scripts/test-read-your-writes.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to the package output directory}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28951; PB=28952
W=${RYW_TEST_DIR:-/tmp/ks-ryw-test}
SOCK=/tmp/ks-ryw-sock; SHARE=/tmp/ks-ryw-share
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
has() { if echo "$2" | grep -q "$3"; then pass "$1"; else fail "$1: '$(echo "$2" | head -c 160)' lacks '$3'"; fi; }
cleanup() { $PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1; $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1; }
cleanup
sudo rm -rf $W $SOCK $SHARE; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
EOC
done
$PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/a.log; exit 1; }
$PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/b.log; exit 1; }
for p in $PA $PB; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb) IS NOT NULL;"
REGB="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb, \"check\"=>false) IS NOT NULL;"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
flushA() { q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
snap() { q $1 spike -c "SELECT count(*) || ':' || md5(string_agg(id||'='||v, ',' ORDER BY id)) FROM t" | tail -1; }
publish() { q $PA spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass)->>'generation'" | tail -1; }
syncB() { q $PB spike -c "SELECT koldstore.sync_from_leader('t'::regclass)->>'generation'" | tail -1; }
# Rewrites cold rows on the leader, flushes, compacts and publishes; leaves B untouched.
round() {
  q $PA spike -c "SET koldstore.hydrate_on_write=on; UPDATE t SET v='r$1-'||id WHERE id BETWEEN 1 AND 60" >/dev/null
  q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
  flushA >/dev/null
  q $PA spike -c "SELECT koldstore.compact_table('t'::regclass)" >/dev/null
  publish >/dev/null
}

say "setup: leader flush + publish, follower adopts"
echo "flush: $(flushA)"
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REGB
$DDL
EOC
q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL" >/dev/null
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
pubn() { q $PA spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass)->>'publication'" | tail -1; }
wait_b() { q $PB spike -c "SELECT koldstore.wait_for_publication('t'::regclass, $1, ${2:-10000})->>'publication'" | tail -1; }
P1=$(pubn); P2=$(pubn)
check "publication numbers increase" "$((P2 - P1))" "1"
check "wait applies the publication" "$(wait_b $P2)" "$P2"
check "follower matches the leader" "$(snap $PB)" "$(snap $PA)"

say "1: a write on the leader is visible after waiting"
q $PA spike -c "SET koldstore.hydrate_on_write=on; UPDATE t SET v='ryw'||id WHERE id BETWEEN 1 AND 60" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
flushA >/dev/null
P3=$(pubn)
OUT=$(q $PB spike -c "SELECT koldstore.wait_for_publication('t'::regclass, $P3)::text" | tail -1)
has "the wait synced" "$OUT" '"synced": true'
check "follower reads the leader's write" "$(q $PB spike -c "SELECT v FROM t WHERE id = 5" | tail -1)" "ryw5"
check "follower matches the leader" "$(snap $PB)" "$(snap $PA)"

say "2: already applied returns at once"
OUT=$(q $PB spike -c "SELECT koldstore.wait_for_publication('t'::regclass, $P3)::text" | tail -1)
has "no second sync" "$OUT" '"synced": false'

say "3: a publication that never comes times out"
T0=$(date +%s)
OUT=$(q $PB spike -c "SELECT koldstore.wait_for_publication('t'::regclass, $((P3 + 100)), 1000)")
T1=$(date +%s)
has "errors on timeout" "$OUT" "timed out"
[ $((T1 - T0)) -le 5 ] && pass "timeout honoured ($((T1 - T0)) s)" || fail "timeout took $((T1 - T0)) s"

say "4: a wait that starts early is released by a later publish"
P4=$((P3 + 1))
( sleep 2; q $PA spike -c "SET koldstore.hydrate_on_write=on; UPDATE t SET v='late'||id WHERE id BETWEEN 1 AND 10" >/dev/null; q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null; flushA >/dev/null; pubn >/dev/null ) &
check "wait returns when the publish lands" "$(wait_b $P4 20000)" "$P4"
wait
check "follower reads the late write" "$(q $PB spike -c "SELECT v FROM t WHERE id = 5" | tail -1)" "late5"
check "follower matches the leader" "$(snap $PB)" "$(snap $PA)"

say "5: publish_for_followers includes a delete the mirror had not applied"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id = 62" >/dev/null
OUT=$(q $PA spike -c "SELECT koldstore.publish_for_followers('t'::regclass)::text" | tail -1)
P5=$(echo "$OUT" | python3 -I -c 'import json,sys; print(json.load(sys.stdin)["publication"])')
check "wait applies it" "$(wait_b $P5)" "$P5"
check "follower hides the delete" "$(q $PB spike -c "SELECT count(*) FROM t WHERE id = 62" | tail -1)" "0"
check "follower matches the leader" "$(snap $PB)" "$(snap $PA)"

cleanup
if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
