#!/usr/bin/env bash
# A flush job queued while this node led must be cancelled, not run, after the lease moved on.
# One scratch cluster; the takeover is simulated by writing a newer lease epoch to the shared storage.
#   KOLDSTORE_PKG=/tmp/kl-stage/pkg-fol scripts/test-lease-queued-job.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to a cargo pgrx package output dir}
ROOT=${LEASE_TEST_DIR:-/tmp/ks-lq}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28931
W=$ROOT/data
SOCK=$ROOT/sock; SHARE=$ROOT/share
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
$PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1
rm -rf "$ROOT"; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
$PG_BIN/initdb -D $W/a -A trust >/dev/null
cat >> $W/a/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
EOC
$PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/a.log; exit 1; }
q $PA postgres -c "CREATE DATABASE spike" >/dev/null
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb) IS NOT NULL;
CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
segs() { q $PA spike -c "SELECT count(*) FROM koldstore.cold_segments WHERE status='active'"; }
jobs() { q $PA spike -c "SELECT coalesce(string_agg(status||'x'||c,','),'none') FROM (SELECT status,count(*) c FROM koldstore.jobs WHERE job_type='flush' GROUP BY 1) x"; }
echo "lease: $(q $PA spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, 3)->>'epoch'")"
echo "segments before: $(segs)"
say "enqueue in an open txn, lease is taken over meanwhile, then commit"
( q $PA spike <<EOC
BEGIN;
SELECT koldstore.enqueue_flush_job('t'::regclass, true) IS NOT NULL;
SELECT pg_sleep(6);
COMMIT;
EOC
) &
sleep 1
mkdir -p $SHARE/_leader_lease/public/t
NOW=$(( $(date +%s) * 1000 ))
echo "{\"epoch\":2,\"holder\":\"someone-else\",\"heartbeat_ms\":$((NOW+60000)),\"ttl_s\":600}" > $SHARE/_leader_lease/public/t/00000000000000000002.json
ls $SHARE/_leader_lease/public/t/
wait
sleep 4
echo "jobs: $(jobs)   segments after: $(segs)  (expect cancelled, unchanged)"
grep -E "lost the leader lease|queued flush" $W/a.log | tail -3 | cut -c1-220
$PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1
