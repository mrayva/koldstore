#!/usr/bin/env bash
# Delete-marker sidecars vs. a follower's read (two scratch clusters, shared filesystem storage,
# the leader's catalog sync worker on). A sidecar that goes away between a follower reading the
# catalog and fetching it must fail the sync closed and recover once the leader republishes; a
# sidecar the CURRENT catalog still lists that is gone must be rewritten by the leader's worker
# without any other change. Pass/fail.
#   KOLDSTORE_PKG=/tmp/kl-stage/pkg-fol scripts/test-sidecar-race.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to the package output directory}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28991; PB=28992
W=${SIDECAR_TEST_DIR:-/tmp/ks-sidecar-test}
SOCK=/tmp/ks-sidecar-sock; SHARE=/tmp/ks-sidecar-share
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
has() { if echo "$2" | grep -q "$3"; then pass "$1"; else fail "$1: '$(echo "$2" | head -c 200)' lacks '$3'"; fi; }
cleanup() { $PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1; $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1; }
trap cleanup EXIT
cleanup
sudo rm -rf $W $SOCK $SHARE; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
EOC
done
cat >> $W/a/postgresql.conf <<EOC
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
koldstore.published_tombstone_limit = 3
EOC
for n in a b; do
  P=$([ $n = a ] && echo $PA || echo $PB)
  $PG_BIN/pg_ctl -D $W/$n -l $W/$n.log -w -o "-p $P -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/$n.log; exit 1; }
  q $P postgres -c "CREATE DATABASE spike" >/dev/null
done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
SC=$SHARE/_leader_tombstones/public/t
cnt() { q $1 spike -c "SELECT count(*) FROM t" | tail -1; }
syncB() { q $PB spike -c "SELECT koldstore.sync_from_leader('t'::regclass)::text" | tail -1; }
nsc() { ls $SC 2>/dev/null | wc -l; }

q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG) IS NOT NULL;
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG, "check" => false) IS NOT NULL;
$DDL
EOC
q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL; SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
for i in $(seq 1 15); do [ -f $SHARE/_leader_catalog/public/t.json ] && break; sleep 1; done
syncB >/dev/null
check "follower starts equal to the leader" "$(cnt $PB)" "$(cnt $PA)"

say "1: six unflushed deletes, inline limit 3: the leader's worker publishes a sidecar"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id IN (10,11,12,13,14,15)" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
for i in $(seq 1 15); do [ "$(nsc)" = 1 ] && break; sleep 1; done
check "one sidecar written by the worker" "$(nsc)" "1"
sleep 3
check "follower masks all six" "$(syncB >/dev/null; cnt $PB)" "294"

say "2: reader race - the sidecar vanishes between catalog read and fetch (leader moved on)"
cp $SC/*.json $W/sidecar.bak; SCF=$(ls $SC/*.json | head -1)
rm -f $SC/*.json
# freeze the leader's worker view: it must not republish before the follower tries
S=$(syncB); echo "sync: ${S:0:170}"
has "the follower fails closed and says why" "$S" "cannot read delete markers"
check "follower data unchanged" "$(cnt $PB)" "294"

say "3: the current catalog still lists the gone sidecar and nothing else changed"
for i in $(seq 1 20); do [ "$(nsc)" = 1 ] && break; sleep 1; done
check "the leader's worker rewrote the sidecar" "$(nsc)" "1"
check "same content" "$(cmp -s $SC/*.json $W/sidecar.bak && echo same || echo different)" "same"
S=$(syncB); echo "sync: ${S:0:120}"
check "the follower syncs again" "$(cnt $PB)" "294"

say "4: a flush retires the markers and their sidecar; a follower that read the old catalog just retries"
q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
for i in $(seq 1 15); do [ -f "$SCF" ] || break; sleep 1; done
check "the superseded sidecar was deleted" "$([ -f "$SCF" ] && echo kept || echo gone)" "gone"
sleep 3
syncB >/dev/null
check "follower agrees with the leader" "$(cnt $PB)" "$(cnt $PA)"
if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
