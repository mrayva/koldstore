#!/usr/bin/env bash
# Atomicity of the lease check: a deposed leader that passed its lease check, stalled, and then
# writes the shared leader catalog after its successor claimed the lease. Storage cannot make
# "check the lease" and "write the catalog" one step, so followers must reject such a write and
# the new leader must repair it. The late write is simulated by overwriting the catalog object
# the way the stalled leader's write would. Three clusters, shared filesystem store. Pass/fail.
#   KOLDSTORE_PKG=/tmp/kl-stage/pkg-fol scripts/test-catalog-fencing.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to a cargo pgrx package output dir}
ROOT=${FENCE_TEST_DIR:-/tmp/ks-fence}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
declare -A PORT=([a]=28981 [b]=28982 [c]=28983)
W=$ROOT/data; SOCK=$ROOT/sock; SHARE=$ROOT/share
CAT=$SHARE/_leader_catalog/public/t.json
TTL=6
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
has() { if echo "$2" | grep -q "$3"; then pass "$1"; else fail "$1: '$(echo "$2" | head -c 240)' lacks '$3'"; fi; }
say() { echo; echo "== $*"; }
cleanup() { for n in a b c; do $PG_BIN/pg_ctl -D $W/$n -m immediate stop >/dev/null 2>&1; done; }
trap cleanup EXIT
cleanup
rm -rf "$ROOT"; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b c; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
EOC
done
start() { $PG_BIN/pg_ctl -D $W/$1 -l $W/$1.log -w -o "-p ${PORT[$1]} -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/$1.log; exit 1; }; }
stop() { $PG_BIN/pg_ctl -D $W/$1 -m immediate stop >/dev/null 2>&1; }
for n in a b c; do start $n; q ${PORT[$n]} postgres -c "CREATE DATABASE spike" >/dev/null; stop $n; start $n; done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
flush() { q ${PORT[$1]} spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
snap() { q ${PORT[$1]} spike -c "SELECT count(*) || ':' || md5(string_agg(id||'='||v, ',' ORDER BY id)) FROM t" | tail -1; }
sync() { q ${PORT[$1]} spike -c "SELECT koldstore.sync_from_leader('t'::regclass)::text" | tail -1; }
cat_epoch() { python3 -I -c "import json;print(json.load(open('$CAT')).get('lease_epoch'))" 2>&1 | tail -1; }

say "setup: A leader (epoch 1) publishes; B and C follow"
q ${PORT[a]} spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG) IS NOT NULL;
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
q ${PORT[a]} spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "flush: $(flush a)"
q ${PORT[a]} spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, $TTL) IS NOT NULL; SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
META=$(q ${PORT[a]} spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
for n in b c; do
  q ${PORT[$n]} spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG, "check" => false) IS NOT NULL;
$DDL
EOC
  q ${PORT[$n]} spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL; SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
done
for i in $(seq 1 10); do [ "$(cat_epoch)" = 1 ] && break; sleep 1; done
check "A published at epoch 1" "$(cat_epoch)" "1"
cp $CAT $ROOT/epoch1.json
check "B follows" "$(snap b)" "$(snap a)"

say "A is deposed: B takes over (epoch 2) and publishes"
stop a
sleep $((TTL + 2))
q ${PORT[b]} spike -c "SELECT koldstore.set_table_follower('t'::regclass, false)" >/dev/null
echo "B acquire: $(q ${PORT[b]} spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, $TTL)::text" | tail -1 | cut -c1-110)"
q ${PORT[b]} spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
q ${PORT[b]} spike -c "INSERT INTO t SELECT g,'b-'||g FROM generate_series(1001,1100) g" >/dev/null
q ${PORT[b]} spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "B flush: $(flush b)"
for i in $(seq 1 10); do [ "$(cat_epoch)" = 2 ] && break; sleep 1; done
check "B published at epoch 2" "$(cat_epoch)" "2"
EPOCH2_SHA=$(sha256sum $CAT | cut -c1-16)
sync c >/dev/null
check "C follows B" "$(snap c)" "$(snap b)"
SEAL=$(python3 -I -c "import json;print(json.load(open('$SHARE/_leader_lease/public/t/00000000000000000002.json')).get('sealed_sha'))")
EXPECT=$(sha256sum $ROOT/epoch1.json | cut -d' ' -f1)
check "the epoch 2 claim sealed the epoch 1 catalog" "$SEAL" "$EXPECT"

say "the stalled old leader's late write lands: epoch 1 content over B's epoch 2 catalog"
python3 -I - <<PY
import json
d=json.load(open("$ROOT/epoch1.json")); d["late_write_from_deposed_leader"]=True
open("$CAT","w").write(json.dumps(d))
PY
check "the catalog object now says epoch 1" "$(cat_epoch)" "1"
BEFORE=$(snap c)
R=$(sync c)
has "C refuses the late write" "$R" "modified after lease epoch 2\|ERROR"
check "C's data is unchanged" "$(snap c)" "$BEFORE"

say "B's sync worker notices and publishes again"
for i in $(seq 1 12); do [ "$(cat_epoch)" = 2 ] && break; sleep 1; done
check "the catalog is epoch 2 again" "$(cat_epoch)" "2"
R=$(sync c)
has "C syncs from the repaired catalog" "$R" "generation"
check "C still agrees with B" "$(snap c)" "$(snap b)"
check "C validates" "$(q ${PORT[c]} spike -c "SELECT koldstore.validate_cold_storage('t'::regclass, true)->>'ok'" | tail -1)" "true"

say "exact pre-claim bytes are still not accepted over a newer epoch"
cp $ROOT/epoch1.json $CAT
R=$(sync c)
has "C refuses an older epoch's catalog" "$R" "older than the epoch\|ERROR"
for i in $(seq 1 12); do [ "$(cat_epoch)" = 2 ] && break; sleep 1; done
check "B repairs that too" "$(cat_epoch)" "2"

if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
