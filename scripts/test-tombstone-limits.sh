#!/usr/bin/env bash
# Limits of the leader's published delete markers (two scratch clusters, shared filesystem
# storage): markers beyond koldstore.published_tombstone_limit ride in checksummed sidecars, only
# past limit x 100 does truncation degrade safely, and a key the follower writes itself is never
# re-masked. Pass/fail.
# Usage: KOLDSTORE_PKG=<cargo pgrx package output dir> [PG_BIN=...] [TLIM_TEST_DIR=...] scripts/test-tombstone-limits.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to the package output directory}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28951; PB=28952
W=${TLIM_TEST_DIR:-/tmp/ks-tlim-test}
SOCK=/tmp/ks-tlim-sock; SHARE=/tmp/ks-tlim-share
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
has() { if echo "$2" | grep -q "$3"; then pass "$1"; else fail "$1: '$(echo "$2" | head -c 200)' lacks '$3'"; fi; }
cleanup() { $PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1; $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1; }
cleanup
sudo rm -rf $W $SOCK $SHARE; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
EOC
done
$PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/a.log; exit 1; }
$PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/b.log; exit 1; }
for p in $PA $PB; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb) IS NOT NULL;"
REGB="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb, \"check\"=>false) IS NOT NULL;"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REGB
$DDL
EOC
q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL" >/dev/null
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
publish() { q $PA spike -c "SET koldstore.published_tombstone_limit=$1; SELECT koldstore.publish_leader_catalog('t'::regclass)::text" | tail -1; }
syncB() { q $PB spike -c "SELECT koldstore.sync_from_leader('t'::regclass)::text" | tail -1; }
cnt() { q $1 spike -c "SELECT count(*) FROM t" | tail -1; }
ids() { q $1 spike -c "SELECT count(*) FROM t WHERE id IN ($2)" | tail -1; }
publish 10000 >/dev/null; syncB >/dev/null
check "follower starts equal to the leader" "$(cnt $PB)" "$(cnt $PA)"

say "1: six unflushed leader deletes, inline limit 3: the rest ride in a checksummed sidecar"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id IN (10,11,12,13,14,15)" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
P=$(publish 3); echo "publish: $P"
has "publish reports all six" "$P" '"tombstones": 6'
has "publish is not truncated" "$P" '"tombstones_truncated": false'
check "one sidecar object written" "$(ls $SHARE/_leader_tombstones/public/t/ 2>/dev/null | wc -l)" "1"
S=$(syncB); echo "sync: $S"
has "follower sync is not truncated" "$S" '"tombstones_truncated": false'
check "follower masks all six at once" "$(cnt $PB)" "294"
check "leader count" "$(cnt $PA)" "294"

say "2: a corrupted sidecar is refused, and the follower keeps what it had"
F=$(ls $SHARE/_leader_tombstones/public/t/*.json | head -1)
cp "$F" $W/sidecar.bak; echo '[{"id": 200}]' > "$F"
S=$(syncB); echo "sync: ${S:0:160}"
has "follower refuses a sidecar that does not match its checksum" "$S" "checksum"
check "follower data unchanged" "$(cnt $PB)" "294"
cp $W/sidecar.bak "$F"
syncB >/dev/null
check "follower syncs again once the sidecar is intact" "$(cnt $PB)" "294"

say "3: past the hard cap (limit x 100) the remainder waits for the leader's flush"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id BETWEEN 100 AND 249" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
P=$(publish 1); echo "publish: $P"
has "publish reports 100 markers" "$P" '"tombstones": 100'
has "publish reports truncation" "$P" '"tombstones_truncated": true'
S=$(syncB)
has "follower sync reports truncation" "$S" '"tombstones_truncated": true'
check "follower masks only the published 100" "$(cnt $PB)" "200"
check "leader count" "$(cnt $PA)" "144"

say "4: limit raised, republished: everything inline, sidecars removed"
P=$(publish 10000); echo "publish: $P"
has "publish reports all 156" "$P" '"tombstones": 156'
has "publish clears the truncation flag" "$P" '"tombstones_truncated": false'
check "stale sidecars deleted" "$(ls $SHARE/_leader_tombstones/public/t/ 2>/dev/null | wc -l)" "0"
S=$(syncB)
has "follower sync clears the flag" "$S" '"tombstones_truncated": false'
check "follower agrees with the leader" "$(cnt $PB)" "$(cnt $PA)"

say "5: a key the follower writes itself is not re-masked"
check "ids 10-15 hidden on the follower" "$(ids $PB 10,11,12,13,14,15)" "0"
OUT=$(q $PB spike -c "INSERT INTO t VALUES (10,'mine')")
echo "follower insert of a masked key: ${OUT:-ok}"
check "the follower sees its own row" "$(q $PB spike -c 'SELECT v FROM t WHERE id=10' | tail -1)" "mine"
syncB >/dev/null; publish 10000 >/dev/null; syncB >/dev/null
check "still visible after more syncs" "$(q $PB spike -c 'SELECT v FROM t WHERE id=10' | tail -1)" "mine"
check "the other five stay hidden" "$(ids $PB 11,12,13,14,15)" "0"
cleanup
if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
