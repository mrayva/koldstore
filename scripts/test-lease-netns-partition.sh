#!/usr/bin/env bash
# True network partition: the tiering leader (A) runs in its own network namespace and keeps
# running while every packet to the S3 endpoint is dropped (not refused). B, outside, takes over
# the lease after the ttl. Then the partition heals and A must be fenced. Pass/fail.
#
# Needs passwordless sudo (ip netns, iptables), socat, an S3-compatible store on 127.0.0.1:18333
# (`weed server -s3`) and a package built with the `s3` feature. The host firewall gets one
# temporary ACCEPT rule for the veth interface; everything is removed on exit.
#   KOLDSTORE_PKG=/tmp/kl-stage/pkg-fol scripts/test-lease-netns-partition.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to a cargo pgrx package output dir built with the s3 feature}
ROOT=${NETNS_TEST_DIR:-/tmp/ks-nsp}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28961; PB=28962
W=$ROOT/data; SOCK=$ROOT/sock
NS=ksnsp; HOSTIP=10.77.0.1; NSIP=10.77.0.2; VH=vkspH; VN=vkspN
export S3_ENDPOINT=${S3_ENDPOINT:-http://127.0.0.1:18333} S3_ACCESS_KEY=${S3_ACCESS_KEY:-x} S3_SECRET_KEY=${S3_SECRET_KEY:-y}
BUCKET=${KOLDSTORE_S3_BUCKET:-spike-bucket}; PFX="nsp-$(date +%s)"
S3PORT=${S3_ENDPOINT##*:}
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
has() { if echo "$2" | grep -q "$3"; then pass "$1"; else fail "$1: '$(echo "$2" | head -c 200)' lacks '$3'"; fi; }
PROXY=
cleanup() {
  $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1
  $PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1
  [ -n "$PROXY" ] && kill "$PROXY" 2>/dev/null
  sudo iptables -D INPUT -i $VH -j ACCEPT 2>/dev/null
  sudo ip link del $VH 2>/dev/null
  sudo ip netns del $NS 2>/dev/null
}
trap cleanup EXIT
cleanup; trap cleanup EXIT
sudo rm -rf "$ROOT"; mkdir -p $W $SOCK
s3() { python3 -I "$(dirname "$0")/lib/s3_tool.py" "$@"; }
s3 mb $BUCKET >/dev/null

say "network: namespace $NS, veth $HOSTIP <-> $NSIP, S3 proxied on $HOSTIP:$S3PORT"
sudo ip netns add $NS && sudo ip link add $VH type veth peer name $VN && sudo ip link set $VN netns $NS \
  && sudo ip addr add $HOSTIP/30 dev $VH && sudo ip link set $VH up \
  && sudo ip netns exec $NS ip addr add $NSIP/30 dev $VN && sudo ip netns exec $NS ip link set $VN up \
  && sudo ip netns exec $NS ip link set lo up || { echo "network setup failed"; exit 1; }
sudo iptables -I INPUT -i $VH -j ACCEPT
socat TCP-LISTEN:$S3PORT,bind=$HOSTIP,fork,reuseaddr TCP:127.0.0.1:$S3PORT &
PROXY=$!
sleep 1
has "namespace reaches S3 through the proxy" "$(sudo ip netns exec $NS python3 -I -c "import urllib.request;print(urllib.request.urlopen('http://$HOSTIP:$S3PORT/').status)" 2>&1)" "200"

for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
EOC
done
chmod 700 $W/a $W/b
# A runs inside the namespace as this user; its unix socket is on the shared filesystem.
stA() { sudo ip netns exec $NS sudo -u "$USER" $PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" "$@" >/dev/null || { tail $W/a.log; exit 1; }; }
stB() { $PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" "$@" >/dev/null || { tail $W/b.log; exit 1; }; }
stA start; stB start
for p in $PA $PB; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
stA restart; stB restart
CFG="{\"region\":\"us-east-1\",\"path_style\":true,\"allow_http\":true"
CREDS="{\"access_key_id\":\"$S3_ACCESS_KEY\",\"secret_access_key\":\"$S3_SECRET_KEY\"}"
URL="s3://$BUCKET/$PFX/"
REGA="SELECT koldstore.register_storage('sh','s3','$URL','$CREDS'::jsonb,'$CFG,\"endpoint\":\"http://$HOSTIP:$S3PORT\"}'::jsonb) IS NOT NULL;"
REGB="SELECT koldstore.register_storage('sh','s3','$URL','$CREDS'::jsonb,'$CFG,\"endpoint\":\"$S3_ENDPOINT\"}'::jsonb, \"check\"=>false) IS NOT NULL;"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REGA
$DDL
CREATE TABLE scratch (n int);
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
flush() { q $1 spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
snap() { q $1 spike -c "SELECT count(*) || ':' || md5(string_agg(id||'='||v, ',' ORDER BY id)) FROM t" | tail -1; }
segs() { q $1 spike -c "SELECT count(*) FROM koldstore.cold_segments WHERE status='active'" | tail -1; }
epoch_pub() { python3 -I - <<PY
import json,subprocess,os
out=subprocess.run(["python3","-I","$(dirname "$0")/lib/s3_tool.py","get","$BUCKET","$PFX/_leader_catalog/public/t.json","/tmp/ks-nsp-cat.json"],capture_output=True,text=True)
try:
    d=json.load(open("/tmp/ks-nsp-cat.json")); print(d.get("lease_epoch"), max(m["generation"] for m in d["manifests"]))
except Exception as e: print("none", e)
PY
}

say "baseline: A leader (lease epoch 1), publishes; B adopts and follows"
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "A flush: $(flush $PA)"
echo "A lease: $(q $PA spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, 8)::text" | tail -1 | cut -c1-100)"
q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
for i in $(seq 1 10); do [ "$(epoch_pub | cut -d' ' -f1)" = 1 ] && break; sleep 1; done
check "A published its catalog at epoch 1" "$(epoch_pub | cut -d' ' -f1)" "1"
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REGB
$DDL
EOC
q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL" >/dev/null
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
q $PB spike -c "SELECT koldstore.sync_from_leader('t'::regclass)" >/dev/null
check "B follows A" "$(snap $PB)" "$(snap $PA)"

say "partition: drop every packet between A's namespace and the S3 endpoint (A keeps running)"
sudo ip netns exec $NS iptables -A OUTPUT -d $HOSTIP -j DROP
sudo ip netns exec $NS iptables -A INPUT -s $HOSTIP -j DROP
T0=$(date +%s)
OUT=$(timeout 180 $PG_BIN/psql -X -q -At -h $SOCK -p $PA -d spike -c "SELECT koldstore.leader_lease_status('t'::regclass)::text" 2>&1 | tail -1)
echo "A lease status under partition ($(( $(date +%s) - T0 ))s): $(echo "$OUT" | cut -c1-200)"
check "A answers within 120s (no unbounded hang)" "$([ $(( $(date +%s) - T0 )) -lt 120 ] && echo yes || echo no)" "yes"
T0=$(date +%s)
OUT=$(timeout 180 $PG_BIN/psql -X -q -At -h $SOCK -p $PA -d spike -c "SET koldstore.flush_execution='inline'; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" 2>&1 | tail -1)
echo "A flush under partition ($(( $(date +%s) - T0 ))s): $(echo "$OUT" | cut -c1-200)"
check "A's flush did not complete" "$(echo "$OUT" | grep -c '^completed')" "0"
check "A still accepts local writes" "$(q $PA spike -c "INSERT INTO scratch VALUES (1); INSERT INTO t VALUES (9001,'partitioned'); SELECT 'ok'" | tail -1)" "ok"

say "B takes over after the ttl (epoch 2) and flushes"
sleep 9
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, false)" >/dev/null
echo "B acquire: $(q $PB spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, 8)::text" | tail -1 | cut -c1-120)"
q $PB spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
q $PB spike -c "INSERT INTO t SELECT g,'b-'||g FROM generate_series(1001,1300) g" >/dev/null
q $PB spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "B flush: $(flush $PB)"
q $PB spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass)->>'generation'" >/dev/null
check "B published at epoch 2" "$(epoch_pub | cut -d' ' -f1)" "2"
PUB=$(epoch_pub); echo "published: $PUB"

say "heal the partition: A is still running and still believes it is the leader"
sudo ip netns exec $NS iptables -F OUTPUT; sudo ip netns exec $NS iptables -F INPUT
sleep 6
R=$(q $PA spike -c "SELECT koldstore.renew_leader_lease('t'::regclass)::text" | tail -1); echo "A renew: $(echo "$R" | cut -c1-160)"
has "A cannot renew" "$R" "lease lost\|epoch 2\|expired"
F=$(q $PA spike -c "SET koldstore.flush_execution='inline'; SELECT koldstore.flush_table('t'::regclass, true)::text" | tail -1); echo "A flush: $(echo "$F" | cut -c1-200)"
has "A cannot flush" "$F" "no longer holds the leader lease\|lease"
P=$(q $PA spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass)::text" | tail -1); echo "A publish: $(echo "$P" | cut -c1-200)"
has "A cannot publish" "$P" "ERROR\|lease"
check "B's published catalog is untouched" "$(epoch_pub)" "$PUB"

say "demote A; it catches up with B"
q $PA spike -c "DELETE FROM t WHERE id = 9001" >/dev/null
q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, false); SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
for i in $(seq 1 15); do [ "$(segs $PA)" = "$(segs $PB)" ] && break; sleep 1; done
q $PA spike -c "SELECT koldstore.sync_from_leader('t'::regclass)" >/dev/null
check "A holds B's segments" "$(segs $PA)" "$(segs $PB)"
check "A and B agree" "$(snap $PA)" "$(snap $PB)"
V=$(q $PA spike -c "SELECT koldstore.validate_cold_storage('t'::regclass, true)->>'ok'" | tail -1)
check "A's cold storage validates" "$V" "true"
if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
