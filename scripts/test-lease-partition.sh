#!/usr/bin/env bash
# Leader loses its view of storage, is then frozen (SIGSTOP) while a follower takes over, and resumes: it must be fenced everywhere.
# Two scratch clusters over a shared filesystem storage; reads like a transcript.
#   KOLDSTORE_PKG=/tmp/kl-stage/pkg-fol scripts/test-lease-partition.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to a cargo pgrx package output dir}
ROOT=${LEASE_TEST_DIR:-/tmp/ks-lp}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28931; PB=28932
W=$ROOT/data
SOCK=$ROOT/sock; SHARE=$ROOT/share; AVIEW=$ROOT/a-view
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
for n in a b; do $PG_BIN/pg_ctl -D $W/$n -m immediate stop >/dev/null 2>&1; done
rm -rf "$ROOT"; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE; ln -s $SHARE $AVIEW
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
EOC
done
st() { $PG_BIN/pg_ctl -D $W/$1 -l $W/$1.log -w -o "-p $2 -k $SOCK $PG_OPTS" "${3:-start}" >/dev/null || { tail $W/$1.log; exit 1; }; }
st a $PA; st b $PB
for p in $PA $PB; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
$PG_BIN/pg_ctl -D $W/a -m fast -w restart -o "-p $PA -k $SOCK $PG_OPTS" >/dev/null
$PG_BIN/pg_ctl -D $W/b -m fast -w restart -o "-p $PB -k $SOCK $PG_OPTS" >/dev/null
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
SELECT koldstore.register_storage('sh','filesystem','$AVIEW','{}'::jsonb,'{}'::jsonb) IS NOT NULL;
CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
flush() { q $1 spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1 | cut -c1-200; }
snap() { q $1 spike -c "SELECT count(*) || ':' || md5(string_agg(id||'='||v, ',' ORDER BY id)) FROM t" | head -1 | cut -c1-120; }
segs() { q $1 spike -c "SELECT count(*) FROM koldstore.cold_segments WHERE status='active'"; }
epoch() { python3 -I -c "import json,sys;print(json.load(open('$SHARE/_leader_catalog/public/t.json')).get('lease_epoch'))" 2>&1 | tail -1; }
echo "A flush: $(flush $PA)"
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "A lease: $(q $PA spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, 6)->>'epoch'")"
echo "A leader: $(q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)")"
sleep 5
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PB spike <<EOC
CREATE EXTENSION koldstore;
SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb, "check"=>false) IS NOT NULL;
CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL;
SELECT koldstore.set_table_follower('t'::regclass, true);
EOC
echo "published epoch: $(epoch)  A segs=$(segs $PA) B segs=$(segs $PB)  B snap=$(snap $PB)"
say "partition A from storage"
rm $AVIEW; ln -s $ROOT/nowhere $AVIEW
sleep 3
echo "A lease status: $(q $PA spike -c "SELECT koldstore.leader_lease_status('t'::regclass)::text" | head -1 | cut -c1-160)"
q $PA spike -c "INSERT INTO t SELECT g,'a-part-'||g FROM generate_series(2000,2049) g" >/dev/null
echo "A flush while partitioned: $(flush $PA)"
echo "A still accepts local writes: $(q $PA spike -c "SELECT count(*) FROM ONLY t WHERE id>=2000")"
rm $AVIEW; ln -s $SHARE $AVIEW
say "freeze A (SIGSTOP the whole cluster, like a paused VM)"
descend() { local p=$1; echo $p; for c in $(ps -o pid= --ppid $p); do descend $c; done; }
APIDS=$(descend $(head -1 $W/a/postmaster.pid))
kill -STOP $APIDS
echo "A frozen: $(echo $APIDS | wc -w) processes"
say "B takes over after ttl"
sleep 8
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, false)" >/dev/null
sleep 1
echo "B acquire: $(q $PB spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, 6)->>'epoch'" | head -1 | cut -c1-120)"
echo "B leader: $(q $PB spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)")"
q $PB spike -c "INSERT INTO t SELECT g,'b-new-'||g FROM generate_series(3000,3199) g" >/dev/null
q $PB spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "B flush: $(flush $PB)"
sleep 3
echo "published epoch: $(epoch)  B segs=$(segs $PB)"
say "resume A"
kill -CONT $APIDS
sleep 5
echo "published epoch after A heals + worker ticks (must stay 2): $(epoch)"
echo "A renew: $(q $PA spike -c "SELECT koldstore.renew_leader_lease('t'::regclass)::text" | head -1 | cut -c1-150)"
echo "A flush after heal: $(flush $PA)"
echo "A publish: $(q $PA spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass)::text" | head -1 | cut -c1-150)"
echo "A log warnings: $(grep -c 'leader lease' $W/a.log)"
say "demote A and catch up"
q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, false); SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
sleep 6
echo "segs A=$(segs $PA) B=$(segs $PB)   B-written rows visible on A: $(q $PA spike -c "SELECT count(*) FROM t WHERE id>=3000")"
echo "A partition-era local rows kept: $(q $PA spike -c "SELECT count(*) FROM t WHERE id BETWEEN 2000 AND 2049")"
for n in a b; do $PG_BIN/pg_ctl -D $W/$n -m immediate stop >/dev/null 2>&1; done
