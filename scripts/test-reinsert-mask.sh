#!/usr/bin/env bash
# A key the leader deleted and then re-inserted (unflushed): a follower that does not replicate the
# leader's hot rows (no Spock) must not return the old, deleted cold version. Two scratch clusters,
# shared filesystem storage. Pass/fail.
#   KOLDSTORE_PKG=/tmp/kl-stage/pkg-fol scripts/test-reinsert-mask.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to the package output directory}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28961; PB=28962
W=${TLIM_TEST_DIR:-/tmp/ks-reinsert}
SOCK=/tmp/ks-reinsert-sock; SHARE=/tmp/ks-reinsert-share
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
has() { if echo "$2" | grep -q "$3"; then pass "$1"; else fail "$1: '$(echo "$2" | head -c 200)' lacks '$3'"; fi; }
cleanup() { $PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1; $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1; }
cleanup
sudo rm -rf $W $SOCK $SHARE; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
EOC
done
$PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/a.log; exit 1; }
$PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/b.log; exit 1; }
for p in $PA $PB; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb) IS NOT NULL;"
REGB="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb, \"check\"=>false) IS NOT NULL;"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REGB
$DDL
EOC
q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL" >/dev/null
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
publish() { q $PA spike -c "SET koldstore.published_tombstone_limit=$1; SELECT koldstore.publish_leader_catalog('t'::regclass)::text" | tail -1; }
syncB() { q $PB spike -c "SELECT koldstore.sync_from_leader('t'::regclass)::text" | tail -1; }
cnt() { q $1 spike -c "SELECT count(*) FROM t" | tail -1; }
ids() { q $1 spike -c "SELECT count(*) FROM t WHERE id IN ($2)" | tail -1; }
publish 10000 >/dev/null; syncB >/dev/null
publish 10000 >/dev/null; syncB >/dev/null
v() { q $1 spike -c "SELECT coalesce((SELECT v FROM t WHERE id=$2),'<none>')" | tail -1; }
recs() { q $PA spike -c "SELECT count(*) FROM koldstore.reinserted_keys" | tail -1; }
flushA() { q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
mirror() { q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null; }
check "start: follower equals leader" "$(v $PB 10)" "$(v $PA 10)"

say "1: delete a cold key, publish: the follower hides it"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id=10" >/dev/null; mirror
publish 10000 >/dev/null; syncB >/dev/null
check "leader" "$(v $PA 10)" "<none>"
check "follower" "$(v $PB 10)" "<none>"

say "2: re-insert it (unflushed): the follower must still not return the old version"
q $PA spike -c "SET koldstore.hydrate_on_write=on; INSERT INTO t VALUES (10,'reborn')" >/dev/null; mirror
check "the re-insert was recorded" "$(recs)" "1"
publish 10000 >/dev/null; syncB >/dev/null
check "leader sees the new row" "$(v $PA 10)" "reborn"
check "follower hides the key (not the old v10)" "$(v $PB 10)" "<none>"

say "3: a plain insert of a new key records nothing; update of a cold key records nothing"
q $PA spike -c "INSERT INTO t VALUES (9001,'fresh')" >/dev/null; mirror
q $PA spike -c "SET koldstore.hydrate_on_write=on; UPDATE t SET v='changed' WHERE id=20" >/dev/null; mirror
check "still one record" "$(recs)" "1"

say "4: delete-then-reinsert inside the same publish window"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id=30" >/dev/null; mirror
q $PA spike -c "SET koldstore.hydrate_on_write=on; INSERT INTO t VALUES (30,'again')" >/dev/null; mirror
publish 10000 >/dev/null; syncB >/dev/null
check "follower hides key 30 as well" "$(v $PB 30)" "<none>"
check "two records" "$(recs)" "2"

say "5: the leader flushes: followers get the new rows, the records are gone"
check "flush" "$(flushA)" "completed"; mirror
publish 10000 >/dev/null; syncB >/dev/null
check "follower returns the new value of 10" "$(v $PB 10)" "reborn"
check "follower returns the new value of 30" "$(v $PB 30)" "again"
check "records pruned" "$(recs)" "0"
check "follower agrees with the leader" "$(cnt $PB)" "$(cnt $PA)"

say "6: delete, re-insert, delete again: stays deleted on the follower"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id=40" >/dev/null; mirror
q $PA spike -c "SET koldstore.hydrate_on_write=on; INSERT INTO t VALUES (40,'x')" >/dev/null; mirror
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id=40" >/dev/null; mirror
publish 10000 >/dev/null; syncB >/dev/null
check "follower" "$(v $PB 40)" "<none>"
cleanup
if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
