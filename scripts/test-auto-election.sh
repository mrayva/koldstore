#!/usr/bin/env bash
# Automatic leader election: three clusters (A leader, B and C followers) over one shared
# filesystem store, koldstore.auto_elect = on everywhere. Kill the leader and exactly one
# follower must claim the next lease epoch, flush, and be followed by the other; restart the old
# leader and it must demote itself and catch up; kill the new leader and the election repeats.
# Pass/fail. Needs a package built from this tree:
#   KOLDSTORE_PKG=/tmp/kl-stage/pkg-fol scripts/test-auto-election.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to a cargo pgrx package output dir}
ROOT=${ELECT_TEST_DIR:-/tmp/ks-elect}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
declare -A PORT=([a]=28971 [b]=28972 [c]=28973)
W=$ROOT/data; SOCK=$ROOT/sock; SHARE=$ROOT/share
TTL=8
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
say() { echo; echo "== $*"; }
cleanup() { for n in a b c; do $PG_BIN/pg_ctl -D $W/$n -m immediate stop >/dev/null 2>&1; done; }
trap cleanup EXIT
cleanup
rm -rf "$ROOT"; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b c; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
koldstore.auto_elect = on
koldstore.leader_lease_ttl_seconds = $TTL
EOC
done
start() { $PG_BIN/pg_ctl -D $W/$1 -l $W/$1.log -w -o "-p ${PORT[$1]} -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/$1.log; exit 1; }; }
stop() { $PG_BIN/pg_ctl -D $W/$1 -m immediate stop >/dev/null 2>&1; }
for n in a b c; do start $n; q ${PORT[$n]} postgres -c "CREATE DATABASE spike" >/dev/null; stop $n; start $n; done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
role() { q ${PORT[$1]} spike -c "SELECT CASE WHEN options->>'leader'='true' THEN 'leader' WHEN options->>'follower'='true' THEN 'follower' ELSE 'none' END || ':' || coalesce(options->>'lease_epoch','-') FROM koldstore.schemas WHERE active AND table_oid='t'::regclass" | tail -1; }
flush() { q ${PORT[$1]} spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
snap() { q ${PORT[$1]} spike -c "SELECT count(*) || ':' || md5(string_agg(id||'='||v, ',' ORDER BY id)) FROM t" | tail -1; }
leaders() { local out=""; for n in "$@"; do case "$(role $n)" in leader:*) out="$out$n";; esac; done; echo "$out"; }
wait_for() { local what=$1 tries=$2; shift 2; for i in $(seq 1 $tries); do if [ "$("$@")" = "ok" ]; then return 0; fi; sleep 1; done; echo "(timed out waiting for $what)"; return 1; }

say "setup: A leader with lease epoch 1; B and C follow"
q ${PORT[a]} spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG) IS NOT NULL;
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
q ${PORT[a]} spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "flush: $(flush a)"
q ${PORT[a]} spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, $TTL) IS NOT NULL; SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
META=$(q ${PORT[a]} spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
for n in b c; do
  q ${PORT[$n]} spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG, "check" => false) IS NOT NULL;
$DDL
EOC
  q ${PORT[$n]} spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL; SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
done
sleep 6
for n in a b c; do echo "$n: $(role $n) $(snap $n)"; done
check "B follows A" "$(snap b)" "$(snap a)"
check "C follows A" "$(snap c)" "$(snap a)"

say "no election while the leader's lease is alive (waiting 2 x ttl)"
sleep $((TTL * 2))
check "still exactly one leader" "$(leaders a b c)" "a"
check "A's epoch is still 1" "$(role a)" "leader:1"

say "kill the leader A"
stop a
for i in $(seq 1 $((TTL * 4))); do [ -n "$(leaders b c)" ] && break; sleep 1; done
sleep 3
NEW=$(leaders b c)
echo "elected: '$NEW'"
check "exactly one follower became leader" "$(echo -n "$NEW" | wc -c)" "1"
[ "${#NEW}" = 1 ] || { echo "== done: $FAILS check(s) FAILED"; exit 1; }
OTHER=$(echo b c | tr -d " $NEW")
check "the new leader holds epoch 2" "$(role $NEW)" "leader:2"
check "the other node is still a follower" "$(role $OTHER | cut -d: -f1)" "follower"

say "the new leader $NEW flushes new rows; $OTHER follows"
q ${PORT[$NEW]} spike -c "INSERT INTO t SELECT g,'n-'||g FROM generate_series(1001,1100) g" >/dev/null
q ${PORT[$NEW]} spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
check "new leader flushes" "$(flush $NEW)" "completed"
for i in $(seq 1 15); do [ "$(snap $NEW)" = "$(snap $OTHER)" ] && break; sleep 1; done
check "follower converges" "$(snap $OTHER)" "$(snap $NEW)"
check "follower validates" "$(q ${PORT[$OTHER]} spike -c "SELECT koldstore.validate_cold_storage('t'::regclass, true)->>'ok'" | tail -1)" "true"

say "restart the old leader A: it must demote itself and catch up"
start a
for i in $(seq 1 30); do [ "$(role a | cut -d: -f1)" = follower ] && break; sleep 1; done
check "A demoted to follower" "$(role a | cut -d: -f1)" "follower"
check "still exactly one leader" "$(leaders a b c)" "$NEW"
for i in $(seq 1 15); do [ "$(snap a)" = "$(snap $NEW)" ] && break; sleep 1; done
check "A converges with the new leader" "$(snap a)" "$(snap $NEW)"

say "kill the new leader $NEW: the election repeats (epoch 3)"
stop $NEW
SURV=$(echo a b c | tr -d "$NEW")
for i in $(seq 1 $((TTL * 4))); do [ -n "$(leaders $SURV | tr -d ' ')" ] && break; sleep 1; done
sleep 3
NEW2=$(leaders a b c | tr -d "$NEW")
echo "elected: '$NEW2'"
check "one survivor leads at epoch 3" "$NEW2:$(role ${NEW2:-a})" "$NEW2:leader:3"

if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
