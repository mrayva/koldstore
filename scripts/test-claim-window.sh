#!/usr/bin/env bash
# The window between an election's catch-up check and its lease claim: a deposed leader's late
# catalog write that lands in it must be adopted by the new leader, not ignored by followers and
# overwritten by the new leader's first publish. Two clusters over one shared filesystem store;
# koldstore.election_claim_delay_ms pauses B's election so the write can be placed exactly. Pass/fail.
# Usage: KOLDSTORE_PKG=<cargo pgrx package output dir> scripts/test-claim-window.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to a cargo pgrx package output dir}
ROOT=${CLAIM_TEST_DIR:-/tmp/ks-claim}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28981; PB=28982
W=$ROOT/data; SOCK=$ROOT/sock; SHARE=$ROOT/share; SCRATCH=$ROOT/scratch
TTL=8; PAUSE=10000
CATALOG=$SHARE/_leader_catalog/public/t.json
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
say() { echo; echo "== $*"; }
cleanup() { for n in a b; do $PG_BIN/pg_ctl -D $W/$n -m immediate stop >/dev/null 2>&1; done; }
trap cleanup EXIT
cleanup
rm -rf "$ROOT"; mkdir -p $W $SOCK $SHARE $SCRATCH; chmod 777 $SHARE
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
koldstore.leader_lease_ttl_seconds = $TTL
EOC
done
# Only B runs the sync worker and elects; A is driven by hand so its writes land when the test says.
cat >> $W/b/postgresql.conf <<EOC
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
koldstore.auto_elect = on
koldstore.election_claim_delay_ms = $PAUSE
EOC
$PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/a.log; exit 1; }
for p in $PA; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
flushA() { q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
snap() { q $1 spike -c "SELECT count(*) || ':' || md5(string_agg(id||'='||v, ',' ORDER BY id)) FROM t" | tail -1; }
gen() { q $1 spike -c "SELECT coalesce(max(generation),0) FROM koldstore.manifest" | tail -1; }
role() { q $PB spike -c "SELECT CASE WHEN options->>'leader'='true' THEN 'leader' WHEN options->>'follower'='true' THEN 'follower' ELSE 'none' END || ':' || coalesce(options->>'lease_epoch','-') FROM koldstore.schemas WHERE table_oid='t'::regclass AND active" | tail -1; }
sha() { sha256sum "$1" | cut -d' ' -f1; }

say "setup: A leads at epoch 1 and publishes X; then flushes more and publishes Y"
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG) IS NOT NULL;
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "flush 1: $(flushA)"
q $PA spike -c "SELECT koldstore.acquire_leader_lease('t'::regclass, $TTL) IS NOT NULL; SELECT koldstore.set_table_leader('t'::regclass, true)" >/dev/null
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PA spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass) IS NOT NULL" >/dev/null
cp $CATALOG $SCRATCH/x.json
G1=$(gen $PA)
q $PA spike -c "INSERT INTO t SELECT g,'late-'||g FROM generate_series(1001,1100) g" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "flush 2: $(flushA)"
q $PA spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass) IS NOT NULL" >/dev/null
cp $CATALOG $SCRATCH/y.json
cp $SCRATCH/x.json $SCRATCH/x.tmp && mv $SCRATCH/x.tmp $CATALOG
G2=$(gen $PA)
[ "$G2" -gt "$G1" ] && pass "Y is a newer generation than X ($G1 -> $G2)" || fail "no newer generation ($G1, $G2)"
cmp -s $SCRATCH/y.json $SCRATCH/x.json && fail "X and Y are identical" || pass "X and Y differ"
A_SNAP=$(snap $PA)

say "B joins as a follower of generation $G1 and watches the silent lease"
$PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/b.log; exit 1; }
q $PB postgres -c "CREATE DATABASE spike" >/dev/null
$PG_BIN/pg_ctl -D $W/b -m fast -w stop >/dev/null; $PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" start >/dev/null
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG, "check" => false) IS NOT NULL;
$DDL
EOC
q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL; SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
check "B holds generation X" "$(gen $PB)" "$G1"

say "B's election pauses before its claim; A's late write (Y) lands in the pause"
for i in $(seq 1 $((TTL * 4))); do grep -q "election pausing" $W/b.log && break; sleep 1; done
grep -q "election pausing" $W/b.log && pass "B started an election" || { fail "B never started an election"; echo "== done: $FAILS check(s) FAILED"; exit 1; }
cp $SCRATCH/y.json $SCRATCH/y.tmp && mv $SCRATCH/y.tmp $CATALOG
echo "Y written over the catalog"

say "after the pause"
for i in $(seq 1 40); do [ "$(role)" = "leader:2" ] && break; sleep 1; done
check "B claimed epoch 2" "$(role)" "leader:2"
SEAL=$(python3 -I -c "import json;print(json.load(open('$SHARE/_leader_lease/public/t/00000000000000000002.json'))['sealed_sha'])")
check "the claim seals Y, the catalog it ended up adopting" "$SEAL" "$(sha $SCRATCH/y.json)"
check "B holds Y's generation" "$(gen $PB)" "$G2"
check "B reads A's late rows" "$(snap $PB)" "$A_SNAP"
for i in $(seq 1 30); do [ "$(python3 -I -c "import json;print(json.load(open('$CATALOG')).get('lease_epoch'))")" = "2" ] && break; sleep 1; done
check "B's first publish went through (catalog stamped epoch 2)" "$(python3 -I -c "import json;print(json.load(open('$CATALOG')).get('lease_epoch'))")" "2"
GP=$(python3 -I -c "import json;c=json.load(open('$CATALOG'));print(max(s.get('generation',0) for s in c['manifests']) if 'manifests' in c else c.get('generation'))" 2>/dev/null)
[ "${GP:-0}" -ge "$G2" ] 2>/dev/null && pass "the published catalog kept Y's generation ($GP)" || fail "published generation $GP is below Y's $G2"
check "B's data is intact after its publish" "$(snap $PB)" "$A_SNAP"
check "B validates" "$(q $PB spike -c "SELECT koldstore.validate_cold_storage('t'::regclass, true)->>'ok'" | tail -1)" "true"

cleanup
if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
