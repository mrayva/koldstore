#!/usr/bin/env bash
# Leader reaping waits for followers: a compacted segment is not deleted while a live follower
# still holds an older generation (two scratch clusters, shared filesystem storage). Pass/fail.
# Usage: KOLDSTORE_PKG=<cargo pgrx package output dir> [PG_BIN=...] [REAP_TEST_DIR=...] scripts/test-reap-follower-guard.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to the package output directory}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28941; PB=28942
W=${REAP_TEST_DIR:-/tmp/ks-reap-test}
SOCK=/tmp/ks-reap-sock; SHARE=/tmp/ks-reap-share
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
FAILS=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILS=$((FAILS + 1)); }
check() { if [ "$2" = "$3" ]; then pass "$1 ($2)"; else fail "$1: got '$2', want '$3'"; fi; }
has() { if echo "$2" | grep -q "$3"; then pass "$1"; else fail "$1: '$(echo "$2" | head -c 160)' lacks '$3'"; fi; }
cleanup() { $PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1; $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1; }
cleanup
sudo rm -rf $W $SOCK $SHARE; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
EOC
done
$PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/a.log; exit 1; }
$PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/b.log; exit 1; }
for p in $PA $PB; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb) IS NOT NULL;"
REGB="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb, \"check\"=>false) IS NOT NULL;"
DDL="CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);"
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG
$DDL
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
flushA() { q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
snap() { q $1 spike -c "SELECT count(*) || ':' || md5(string_agg(id||'='||v, ',' ORDER BY id)) FROM t" | tail -1; }
publish() { q $PA spike -c "SELECT koldstore.publish_leader_catalog('t'::regclass)->>'generation'" | tail -1; }
syncB() { q $PB spike -c "SELECT koldstore.sync_from_leader('t'::regclass)->>'generation'" | tail -1; }
reapA() { q $PA spike -c "SELECT koldstore.reap_compacted_segments('t'::regclass, 0)"; }
compacted() { q $PA spike -c "SELECT count(*) FROM koldstore.cold_segments WHERE status='compacted'" | tail -1; }
acks() { ls $SHARE/_follower_acks/public/t/ 2>/dev/null | wc -l; }
# Rewrites cold rows on the leader, flushes, compacts and publishes; leaves B untouched.
round() {
  q $PA spike -c "SET koldstore.hydrate_on_write=on; UPDATE t SET v='r$1-'||id WHERE id BETWEEN 1 AND 60" >/dev/null
  q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
  flushA >/dev/null
  q $PA spike -c "SELECT koldstore.compact_table('t'::regclass)" >/dev/null
  publish >/dev/null
}

say "setup: leader flush + publish, follower adopts and syncs"
echo "flush: $(flushA)"
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "leader: $(q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)")"
G0=$(publish)
META=$(q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text")
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REGB
$DDL
EOC
q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL" >/dev/null
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, true)" >/dev/null
check "follower announced itself before its first sync" "$(acks)" "1"
check "follower syncs to the published generation" "$(syncB)" "$G0"
check "follower wrote one acknowledgement" "$(acks)" "1"

say "1: leader compacts and publishes; follower has not synced"
round 1
echo "compacted segments on leader: $(compacted)"
[ "$(compacted)" -gt 0 ] && pass "compaction left segments to reap" || fail "no compacted segments"
OUT=$(reapA)
has "reap refused while the follower is behind" "$OUT" "has not caught up"
check "nothing reaped (compacted segments remain)" "$([ "$(compacted)" -gt 0 ] && echo kept || echo gone)" "kept"
check "follower still reads (old catalog, old objects present)" "$(snap $PB | cut -d: -f1)" "300"

say "2: follower syncs, acknowledges, then the reap proceeds"
G1=$(publish)
check "follower syncs to the new generation" "$(syncB)" "$G1"
OUT=$(reapA)
if echo "$OUT" | grep -q ERROR; then fail "reap after catch-up: $OUT"; else pass "reap after catch-up ($(echo "$OUT" | tail -1))"; fi
check "compacted segments gone" "$(compacted)" "0"
check "leader and follower agree" "$(snap $PB)" "$(snap $PA)"

say "3: a follower silent past the max age no longer blocks"
round 2
has "refused again while the ack is fresh" "$(reapA)" "has not caught up"
sleep 2
q $PA spike -c "SET koldstore.follower_ack_max_age_seconds=1; SELECT koldstore.reap_compacted_segments('t'::regclass, 0)" > $W/reap3.out
if grep -q ERROR $W/reap3.out; then fail "reap with an expired ack: $(cat $W/reap3.out)"; else pass "reap proceeds once the ack is older than the max age"; fi
echo "follower read while its segments are gone: $(snap $PB | head -c 100)"
G2=$(publish)
check "follower heals on its next sync" "$(syncB)" "$G2"
check "leader and follower agree after the heal" "$(snap $PB)" "$(snap $PA)"

say "4: the check can be switched off"
round 3
has "refused with the default setting" "$(reapA)" "has not caught up"
q $PA spike -c "SET koldstore.follower_ack_max_age_seconds=0; SELECT koldstore.reap_compacted_segments('t'::regclass, 0)" > $W/reap4.out
if grep -q ERROR $W/reap4.out; then fail "reap with the check off: $(cat $W/reap4.out)"; else pass "reap proceeds with follower_ack_max_age_seconds = 0"; fi
syncB >/dev/null
check "follower converges" "$(snap $PB)" "$(snap $PA)"

say "5: a sync that rolls back does not acknowledge"
ackgen() { python3 -I -c "import json,glob;print(json.load(open(glob.glob('$SHARE/_follower_acks/public/t/*.json')[0]))['generation'])"; }
round 5
G5=$(publish)
BEFORE=$(ackgen)
q $PB spike -c "BEGIN; SELECT koldstore.sync_from_leader('t'::regclass); ROLLBACK;" >/dev/null
check "the rolled-back sync left the acknowledgement alone" "$(ackgen)" "$BEFORE"
has "so the leader still waits for the follower" "$(reapA)" "has not caught up"
syncB >/dev/null
check "a committed sync acknowledges" "$(ackgen)" "$G5"

say "6: a node that stops following no longer holds reaping back"
round 6
has "refused while the follower lags" "$(reapA)" "has not caught up"
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, false)" >/dev/null
check "turning follower mode off removed the acknowledgement" "$(acks)" "0"
OUT=$(reapA)
if echo "$OUT" | grep -q ERROR; then fail "reap after the follower left: $OUT"; else pass "reap proceeds once the follower left"; fi

cleanup
if [ "$FAILS" -eq 0 ]; then echo; echo "== done: all checks passed"; else echo; echo "== done: $FAILS check(s) FAILED"; exit 1; fi
