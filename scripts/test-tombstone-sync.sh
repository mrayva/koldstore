#!/usr/bin/env bash
# Tombstone sync from a tiering leader to a follower (two scratch clusters, shared filesystem
# storage). Prints a transcript with the expected value beside each check.
# Usage: KOLDSTORE_PKG=<cargo pgrx package output dir> [PG_BIN=...] [TOMB_TEST_DIR=...] scripts/test-tombstone-sync.sh
set -uo pipefail
PG_BIN=${PG_BIN:-/usr/lib/postgresql/18/bin}
PKG=${KOLDSTORE_PKG:?set KOLDSTORE_PKG to the package output directory}
PG_OPTS="-c dynamic_library_path='$PKG/usr/lib/postgresql/18/lib:\$libdir' -c extension_control_path='$PKG/usr/share/postgresql/18:\$system'"
PA=28931; PB=28932
W=${TOMB_TEST_DIR:-/tmp/ks-tomb-test}
SOCK=/tmp/ks-fol-sock; SHARE=/tmp/ks-fol-share
q() { local port=$1 db=$2; shift 2; $PG_BIN/psql -X -q -At -h $SOCK -p $port -d $db "$@" 2>&1 | grep -v pg_circuit; }
say() { echo; echo "== $*"; }
$PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1; $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1
sudo rm -rf $W $SOCK $SHARE; mkdir -p $W $SOCK $SHARE; chmod 777 $SHARE
for n in a b; do
  $PG_BIN/initdb -D $W/$n -A trust >/dev/null
  cat >> $W/$n/postgresql.conf <<EOC
shared_preload_libraries = 'koldstore'
wal_level = logical
max_replication_slots = 10
max_wal_senders = 10
max_worker_processes = 40
EOC
done
cat >> $W/a/postgresql.conf <<EOC
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
EOC
cat >> $W/b/postgresql.conf <<EOC
koldstore.catalog_sync_interval_seconds = 2
koldstore.catalog_sync_databases = 'spike'
EOC
$PG_BIN/pg_ctl -D $W/a -l $W/a.log -w -o "-p $PA -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/a.log; exit 1; }
$PG_BIN/pg_ctl -D $W/b -l $W/b.log -w -o "-p $PB -k $SOCK $PG_OPTS" start >/dev/null || { tail $W/b.log; exit 1; }
for p in $PA $PB; do q $p postgres -c "CREATE DATABASE spike" >/dev/null; done
$PG_BIN/pg_ctl -D $W/a -m fast -w restart -o "-p $PA -k $SOCK $PG_OPTS" >/dev/null
$PG_BIN/pg_ctl -D $W/b -m fast -w restart -o "-p $PB -k $SOCK $PG_OPTS" >/dev/null
REG="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb) IS NOT NULL;"
REGB="SELECT koldstore.register_storage('sh','filesystem','$SHARE','{}'::jsonb,'{}'::jsonb, \"check\"=>false) IS NOT NULL;"
q $PA spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REG
CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
SET koldstore.min_max_rows_per_file=1;
SELECT koldstore.manage_table('t'::regclass, storage=>'sh', hot_row_limit=>20, min_flush_rows=>1, max_rows_per_file=>100, auto_flush=>false) IS NOT NULL;
EOC
flushA() { q $PA spike -c "SET koldstore.flush_execution='inline'; SET koldstore.min_max_rows_per_file=1; SELECT koldstore.flush_table('t'::regclass, true)->>'status'" | tail -1; }
say "leader flush + publish"
echo "flush: $(flushA)"
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "set_table_leader: $(q $PA spike -c "SELECT koldstore.set_table_leader('t'::regclass, true)")"
for i in 1 2 3 4 5 6; do q $PA spike -c "SELECT 1" >/dev/null; [ -f $SHARE/_leader_catalog/public/t.json ] && break; sleep 1; done
echo "auto-published: $(ls $SHARE/_leader_catalog/public/ 2>&1)"
say "follower B adopts, marked follower"
HOT=$(q $PA spike -c "SELECT string_agg(id::text, ',') FROM t")
q $PA spike -c "SELECT koldstore.export_table_metadata('t'::regclass)::text" > $W/meta.json
META=$(cat $W/meta.json)
q $PB spike >/dev/null <<EOC
CREATE EXTENSION koldstore;
$REGB
CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text NOT NULL);
INSERT INTO t SELECT g, 'v' || g FROM generate_series(1, 300) g;
UPDATE t SET v='edited' WHERE id=5;
EOC
echo "adopt: $(q $PB spike -c "SET koldstore.min_max_rows_per_file=1; SELECT koldstore.import_table_metadata('t'::regclass, \$m\$$META\$m\$::jsonb) IS NOT NULL" | tail -1)"
segs() { q $1 spike -c "SELECT count(*) FROM koldstore.cold_segments WHERE status='active'"; }
echo "segments A=$(segs $PA) B=$(segs $PB)"
echo "follower on leader table refused? $(q $PA spike -c "SELECT koldstore.set_table_follower('t'::regclass, true)" | head -1 | cut -c1-120)"
echo "set_table_follower: $(q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass, true)")"
echo "options: $(q $PB spike -c "SELECT options::text FROM koldstore.schemas WHERE active AND table_oid='t'::regclass")"
heapn() { q $1 spike -c "CREATE EXTENSION IF NOT EXISTS pageinspect; SELECT count(*) FROM generate_series(0, GREATEST(pg_relation_size('t')/8192-1,0)) p, heap_page_items(get_raw_page('t',p::int)) i WHERE i.lp_flags=1 AND (i.t_xmax=0 OR (i.t_infomask & 128)<>0 OR (i.t_infomask & 2048)<>0)" | tail -1; }


heapc() { q $1 spike -c "SELECT count(*) FROM ONLY t WHERE id IN ($2)"; }
syn() { q $1 spike -c "SELECT count(*) FROM $(q $1 spike -c "SELECT mirror_relation::text FROM koldstore.schemas WHERE active AND table_oid='t'::regclass") WHERE op=3 AND seq<0"; }
waitsegs() { for i in $(seq 1 10); do [ "$(segs $PB)" = "$(segs $PA)" ] && break; sleep 1; done; }
say "A: leader deletes 40,41,42 (follower still has unpruned equal hot copies; id 43 edited on follower, then deleted on leader)"
q $PB spike -c "UPDATE t SET v='mine' WHERE id=43" >/dev/null
echo "follower hot copies 40-43 before: $(heapc $PB 40,41,42,43)"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id IN (40,41,42,43)" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "flush: $(flushA)"
waitsegs
echo "segments A=$(segs $PA) B=$(segs $PB)"
echo "follower hot copies 40-43 after sync: $(heapc $PB 40,41,42,43) (expect 1: the edited 43)  visible ids 40-42: $(q $PB spike -c 'SELECT count(*) FROM t WHERE id IN (40,41,42)') (expect 0)"
echo "prune: $(q $PB spike -c "SELECT koldstore.prune_follower_hot('t'::regclass)::text" | tail -1)"
say "B: leader deletes 10,11,12 (NOT flushed); follower already cold-only"
echo "follower sees 10-12: $(q $PB spike -c 'SELECT count(*) FROM t WHERE id IN (10,11,12)')"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id IN (10,11,12)" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
for i in $(seq 1 12); do [ "$(q $PB spike -c 'SELECT count(*) FROM t WHERE id IN (10,11,12)')" = 0 ] && break; sleep 1; done
echo "follower sees 10-12 after worker tick (waited ${i}s): $(q $PB spike -c 'SELECT count(*) FROM t WHERE id IN (10,11,12)') (expect 0)  synthetic markers: $(syn $PB)"
echo "catalog tombstones: $(python3 -I -c "import json;d=json.load(open('$SHARE/_leader_catalog/public/t.json'));print(len(d.get('tombstones',[])), d.get('tombstones',[])[:2])")"
echo "follower count=$(q $PB spike -c 'SELECT count(*) FROM t') leader count=$(q $PA spike -c 'SELECT count(*) FROM t')"
say "B2: leader re-inserts 11, then flushes"
q $PA spike -c "SET koldstore.hydrate_on_write=on; INSERT INTO t VALUES (11,'again')" >/dev/null
q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null
echo "flush: $(flushA)"
waitsegs; sleep 3
echo "follower id 11: $(q $PB spike -c 'SELECT v FROM t WHERE id=11') ids 10,12: $(q $PB spike -c 'SELECT count(*) FROM t WHERE id IN (10,12)') synthetic: $(syn $PB)"
echo "follower count=$(q $PB spike -c 'SELECT count(*) FROM t') leader count=$(q $PA spike -c 'SELECT count(*) FROM t')"
echo "validate B: $(q $PB spike -c "SELECT * FROM koldstore.validate_cold_storage('t'::regclass, true)" | tail -2 | cut -c1-200)"
say "promote B: follower off clears synthetic markers"
q $PA spike -c "SET koldstore.hydrate_on_write=on; DELETE FROM t WHERE id=20" >/dev/null; q $PA spike -c "SELECT koldstore.wait_for_async_mirror() IS NOT NULL" >/dev/null; sleep 4
echo "synthetic before: $(syn $PB)"
q $PB spike -c "SELECT koldstore.set_table_follower('t'::regclass,false)" >/dev/null
echo "synthetic after: $(syn $PB)"
$PG_BIN/pg_ctl -D $W/a -m immediate stop >/dev/null 2>&1; $PG_BIN/pg_ctl -D $W/b -m immediate stop >/dev/null 2>&1
echo "== done"
